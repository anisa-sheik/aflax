// Real Madani Mushaf page images (King Fahd Complex rendering, generated by quran.com-images).
// Source: github.com/GovarJabbar/Quran-PNG (mirror of quran.com-images PNG output).
// Served via jsDelivr for a fast global CDN.
export function mushafImageUrl(page: number): string {
  const p = Math.max(1, Math.min(TOTAL_PAGES, page));
  const padded = String(p).padStart(3, "0");
  return `https://cdn.jsdelivr.net/gh/GovarJabbar/Quran-PNG@master/${padded}.png`;
}

// Resolve a page → containing surah / juz.
export function pageToSurah(page: number): number {
  let last = 1;
  for (const [s, p] of Object.entries(SURAH_START_PAGE)) {
    if (p <= page) last = Number(s); else break;
  }
  return last;
}
export function pageToJuz(page: number): number {
  let last = 1;
  for (const [j, p] of Object.entries(JUZ_START_PAGE)) {
    if (p <= page) last = Number(j); else break;
  }
  return last;
}
