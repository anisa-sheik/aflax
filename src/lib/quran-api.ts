// Lightweight Qur'an API client (alquran.cloud) — Arabic only.
// Supports surah-based and page-based (Madinah Mushaf) fetching.

import { tajweedToHtml, tajweedToPlain } from "./quran-tajweed";

export type Surah = {
  number: number;
  name: string;
  englishName: string;
  englishNameTranslation: string;
  numberOfAyahs: number;
  revelationType: string;
};

export type Ayah = {
  number: number;
  numberInSurah: number;
  arabic: string;
  tajweedHtml: string;
  page: number;
  juz: number;
  surah: { number: number; name: string; englishName: string };
};

const BASE = "https://api.alquran.cloud/v1";
export const TOTAL_PAGES = 604;

let _surahCache: Surah[] | null = null;
export async function fetchSurahs(): Promise<Surah[]> {
  if (_surahCache) return _surahCache;
  const r = await fetch(`${BASE}/surah`);
  const j = await r.json();
  _surahCache = j.data as Surah[];
  return _surahCache;
}

const _pageCache = new Map<number, Ayah[]>();
export async function fetchPage(page: number): Promise<Ayah[]> {
  if (_pageCache.has(page)) return _pageCache.get(page)!;
  const r = await fetch(`${BASE}/page/${page}/quran-tajweed`);
  const j = await r.json();
  const list: Ayah[] = (j.data.ayahs as any[]).map((a) => ({
    number: a.number,
    numberInSurah: a.numberInSurah,
    arabic: tajweedToPlain(a.text),
    tajweedHtml: tajweedToHtml(a.text),
    page: a.page,
    juz: a.juz,
    surah: { number: a.surah.number, name: a.surah.name, englishName: a.surah.englishName },
  }));
  _pageCache.set(page, list);
  return list;
}

